using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Rmut.Cli;

internal static class SourceProjection
{
    public static bool IsGenerated(string path, SyntaxNode root) =>
        path.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase) ||
        root.GetLeadingTrivia().Any(trivia =>
            (trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) || trivia.IsKind(SyntaxKind.MultiLineCommentTrivia)) &&
            (trivia.ToString().Contains("<auto-generated", StringComparison.Ordinal) ||
                trivia.ToString().Contains("<autogenerated", StringComparison.Ordinal)));

    public static string? ActiveText(string source, SyntaxNode root)
    {
        if (!source.Contains('#'))
            return null;

        var hidden = root.DescendantTrivia().Where(trivia => trivia.Kind() is SyntaxKind.DisabledTextTrivia
            or SyntaxKind.IfDirectiveTrivia or SyntaxKind.ElifDirectiveTrivia or SyntaxKind.ElseDirectiveTrivia
            or SyntaxKind.EndIfDirectiveTrivia or SyntaxKind.DefineDirectiveTrivia or SyntaxKind.UndefDirectiveTrivia);
        StringBuilder? active = null;
        var previous = 0;
        foreach (var trivia in hidden)
        {
            var span = trivia.FullSpan;
            active ??= new StringBuilder(source.Length);
            active.Append(source.AsSpan(previous, span.Start - previous));
            // Keep tree-sitter's UTF-8 byte positions valid in the original source.
            foreach (var rune in source.AsSpan(span.Start, span.Length).EnumerateRunes())
            {
                if (rune.Value is '\r' or '\n' or 0x85 or 0x2028 or 0x2029)
                    active.Append(rune.ToString());
                else
                    active.Append(' ', rune.Utf8SequenceLength);
            }
            previous = span.End;
        }
        return active?.Append(source.AsSpan(previous)).ToString();
    }
}
